# 场景主图人物短语清洗：LLM 写场景氛围时容易把「一桌两人/食客若干」当陈设
# 写进提示词——场景图带人物会破坏「空镜锚点」语义（人物由分镜生成时单独注入）
_SCENE_FIGURE_RE = re.compile(
    r"[，,；;、]?\s*"
    r"(?:[一二两三四五六七八九十几0-9]+\s*桌\s*[一二两三四五六七八九十几0-9]+\s*人"
    r"|[一二两三四五六七八九十几0-9]+\s*[位名个]?\s*(?:食客|客人|顾客|路人|人影|剪影)"
    r"|人群|(?:人物)?剪影)"
)


def strip_scene_figures(text: str) -> str:
    """清洗场景主图提示词中的人物相关短语。

    两类都要清：①「一桌两人/食客若干」等含人计数的陈设描述；②「严禁出现
    任何人物」「空无一人」等否定式措辞——否定句里的人脸名词会在弱生成模型
    上反向触发（浮空人脸事故），场景提示词必须为纯正向描述、不含任何含
    「人」的字样。
    """
    cleaned = _SCENE_FIGURE_RE.sub("", text or "")
    cleaned = re.sub(
        r"[，,；;、]?\s*(?:画面中)?(?:严禁|禁止|不得|不要|无|没有|不含|空无)"
        r"[^，,。；;]{0,14}(?:人物|人影|人脸|人体|一人)[^，,。；;]*",
        "", cleaned)
    return cleaned.strip().rstrip("，,；;、").strip()


# 「按名单剔句」的切分边界：在标点**之后**切开，标点留在前一段（保住行文节奏）
_CLAUSE_SPLIT_RE = re.compile(r"(?<=[，,；;。、])")


def strip_figure_clauses(text: str, names: list[str] | None = None) -> str:
    """按**角色名单**剔除含人物名的整句（确定性对账，不是猜词）。

    实测泄漏（2026-10-02 用户反馈，场景图里出现了妈妈）：解析把人物走位写进了
    「空间布局」——「厨房门洞与布帘在左后方，妈妈可站在布帘后探头看向沙发」
    「小杰坐对面背朝房门」——而布局段是原样拼进生图提示词的。名字来自项目角色
    表（解析落库的语义结果），含名单角色的分句**整句剔除**（该句携带的是人物
    调度，属于分镜层，不是场景的静态空间信息）。名单对账属于「代码执行模型的
    语义判断结果」，不猜同义词、不做模糊匹配。

    只对 **≥2 字** 的名字生效：单字名（如「林」）做子串匹配会误伤普通词
    （树林/林荫道），宁缺毋滥——单字名角色由解析侧提示词规则约束。
    """
    keys = [n.strip() for n in (names or []) if n and len(n.strip()) >= 2]
    if not keys or not text:
        return text or ""
    kept = [seg for seg in _CLAUSE_SPLIT_RE.split(text)
            if not any(k in seg for k in keys)]
    return "".join(kept).strip().strip("，,；;、").strip()


